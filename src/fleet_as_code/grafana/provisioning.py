"""Render every Grafana provisioning file and the dashboard JSON from Python, or check they are up to date.

Layout (mounted into the container as /etc/grafana/provisioning and /var/lib/grafana/dashboards):
    grafana/provisioning/datasources/influxdb.yaml
    grafana/provisioning/dashboards/fleet.yaml
    grafana/provisioning/alerting/fleet-rules.yaml
    grafana/dashboards/<uid>.json

Secrets and host names stay out of the files: Grafana expands ${INFLUX_URL}, ${INFLUX_TOKEN} and
${FLEET_DASHBOARDS_DIR} from its environment when it loads them.

Usage:
    from fleet_as_code.grafana.provisioning import render, write, stale
    write(render(speed=60), Path("grafana"))
    stale(render(), Path("grafana"))   # -> list of files that differ
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from fleet_as_code import config
from fleet_as_code.grafana.alerts import rules_file
from fleet_as_code.grafana.dashboards import build_all

HEADER = "# Generated by `python -m fleet_as_code generate` - do not edit by hand.\n"


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, s: str):
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)


_Dumper.add_representer(str, _str)


def _yaml(doc: dict) -> str:
    return HEADER + yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


def datasource() -> dict:
    return {"apiVersion": 1, "datasources": [{
        "name": "InfluxDB fleet", "uid": config.DATASOURCE_UID, "type": "influxdb", "access": "proxy",
        "url": "${INFLUX_URL}", "isDefault": True, "editable": False,
        "jsonData": {"version": "Flux", "organization": config.INFLUX_ORG, "defaultBucket": config.BUCKET,
                     "timeInterval": "1s", "httpMode": "POST"},
        "secureJsonData": {"token": "${INFLUX_TOKEN}"}}]}


def dashboard_provider() -> dict:
    return {"apiVersion": 1, "providers": [{
        "name": "fleet", "orgId": 1, "folder": config.FOLDER_TITLE, "folderUid": config.FOLDER_UID, "type": "file",
        "disableDeletion": True, "allowUiUpdates": False, "updateIntervalSeconds": 30,
        "options": {"path": "${FLEET_DASHBOARDS_DIR}", "foldersFromFilesStructure": False}}]}


def render(speed: float = config.SPEED) -> dict[str, str]:
    """Relative path -> file content."""
    dashboards = build_all(speed)
    panel_ids = {(d["uid"], p["title"]): p["id"] for d in dashboards for p in d["panels"]}
    files = {
        "provisioning/datasources/influxdb.yaml": _yaml(datasource()),
        "provisioning/dashboards/fleet.yaml": _yaml(dashboard_provider()),
        "provisioning/alerting/fleet-rules.yaml": _yaml(rules_file(speed, panel_ids)),
        "provisioning/plugins/.gitkeep": "",   # Grafana logs an error when a provisioning folder is missing
    }
    for d in dashboards:
        files[f"dashboards/{d['uid']}.json"] = json.dumps(d, indent=2, ensure_ascii=False) + "\n"
    return files


def write(files: dict[str, str], out_dir: Path) -> None:
    for rel, content in files.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def stale(files: dict[str, str], out_dir: Path) -> list[str]:
    out = []
    for rel, content in files.items():
        path = out_dir / rel
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            out.append(rel)
    return out
